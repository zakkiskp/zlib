const LanguageContext = createContext(null);
const STORAGE_KEY = 'zlib_lang';

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    if (typeof window === 'undefined') return 'id';
    return localStorage.getItem(STORAGE_KEY) || 'id';
  });

  useEffect(() => {
    document.documentElement.setAttribute('lang', lang);
  }, [lang]);

  function setLang(next) {
    setLangState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
    } catch (e) {
      // storage penuh/diblokir browser — abaikan, cukup state React yang jalan
    }
  }

  /**
   * t(key, vars?) — mendukung interpolasi variabel sederhana.
   * Contoh: t('common.pagination', { from: 1, to: 15, total: 42 })
   * dengan key berisi "Menampilkan {{from}}–{{to}} dari {{total}}".
   */
  function t(key, vars) {
    let str = translations[lang]?.[key] ?? translations.id[key] ?? key;
    if (vars) {
      Object.entries(vars).forEach(([k, v]) => {
        str = str.replace(new RegExp(`{{${k}}}`, 'g'), v);
      });
    }
    return str;
  }

  return (
    <LanguageContext.Provider value={{ lang, setLang, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    throw new Error('useLanguage() harus dipakai di dalam <LanguageProvider>. Lihat README untuk cara wrap root app.');
  }
  return ctx;
}
